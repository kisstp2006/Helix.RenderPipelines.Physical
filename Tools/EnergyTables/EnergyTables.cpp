// Writes the OpenPBR energy tables the Physical pipeline embeds: EnergyTables.inl beside EnergyIntegration.h.
// Usage: helix_physical_energy_tables <output file>
#include <Helix/RenderPipelines/Physical/Energy/EnergyIntegration.h>

#include <cstdio>

using namespace helix;
using namespace helix::rendering::physical::energy;

namespace
{
    // A float literal of nine significant digits (always with a point: 1 is 1.0f).
    const char* Literal(f64 v, char (&out)[48])
    {
        char digits[40];
        std::snprintf(digits, sizeof(digits), "%.9g", v);
        bool point = false;
        for (const char* c = digits; *c; c++)
            point = point || *c == '.' || *c == 'e';
        std::snprintf(out, sizeof(out), "%s%sf", digits, point ? "" : ".0");
        return out;
    }
}

int main(int argc, char** argv)
{
    if (argc < 2)
    {
        std::fprintf(stderr, "usage: helix_physical_energy_tables <output file>\n");
        return 1;
    }
    std::FILE* f = std::fopen(argv[1], "wb");
    if (!f)
    {
        std::fprintf(stderr, "cannot write %s\n", argv[1]);
        return 1;
    }
    std::fprintf(f, "// Generated by Tools/EnergyTables (helix_physical_energy_tables); do not edit.\n");
    std::fprintf(f, "// kTable: per roughness row (r = j / %d) and cosine column (mu = i / %d): GGX A, B, C and the FON lobe's E.\n", kSize - 1, kSize - 1);
    std::fprintf(f, "// kAverage: per roughness: the GGX lobe's and the FON lobe's albedo averaged over the hemisphere.\n");
    std::fprintf(f, "#pragma once\n\nnamespace helix::rendering::physical::energy\n{\n");
    std::fprintf(f, "    inline constexpr float kTable[%d] = {\n", kSize * kSize * 4);
    for (i32 j = 0; j < kSize; j++)
    {
        for (i32 i = 0; i < kSize; i++)
        {
            f64 mu = NodeCosine(i), r = NodeRoughness(j);
            GgxAlbedo g = IntegrateGgx(mu, r);
            f64 fon = IntegrateFon(mu, r);
            char a[48], b[48], c[48], e[48];
            std::fprintf(f, "%s%s, %s, %s, %s,", i == 0 ? "        " : " ", Literal(g.a, a), Literal(g.b, b), Literal(g.c, c), Literal(fon, e));
        }
        std::fprintf(f, "\n");
        std::fprintf(stderr, "row %d of %d\n", j + 1, kSize);
    }
    std::fprintf(f, "    };\n\n    inline constexpr float kAverage[%d] = {\n", kSize * 2);
    for (i32 j = 0; j < kSize; j++)
    {
        char a[48], b[48];
        std::fprintf(f, "        %s, %s,\n", Literal(AverageGgx(NodeRoughness(j)), a), Literal(AverageFon(NodeRoughness(j)), b));
    }
    std::fprintf(f, "    };\n}\n");
    std::fclose(f);
    return 0;
}
